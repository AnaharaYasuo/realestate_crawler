import pytest
from bs4 import BeautifulSoup
from unittest.mock import MagicMock, patch
from package.parser.baseParser import (
    ParserBase,
    ListingEndedException,
    SiteMaintenanceException,
    AccessBlockedException,
    ParserFailureException,
    check_access_blocked_or_maintenance,
)
from package.api.api import ParseDetailPageAsyncBase


class DummyEntity:
    pass

class ConcreteTestProc(ParseDetailPageAsyncBase):
    def _generateParser(self):
        parser = MagicMock()
        parser.company = "testco"
        parser.property_type = "mansion"
        parser.createEntity.return_value = DummyEntity()
        return parser

    def _getLocalPararellLimit(self): return 1
    def _getCloudPararellLimit(self): return 1
    def _getTimeOutSecond(self): return 5
    def _getApiKey(self): return ""


def test_access_blocked_detection_geetest():
    """GeeTest CAPTCHA画面で AccessBlockedException が送出され、ListingEndedException とならないこと"""
    html = "<html><head><title>【アットホーム】認証中</title></head><body><div class='center'>認証にご協力ください</div></body></html>"
    soup = BeautifulSoup(html, "html.parser")
    with pytest.raises(AccessBlockedException):
        check_access_blocked_or_maintenance(soup, 200, "https://example.com/test")


def test_access_blocked_detection_cloudfront_403():
    """CloudFront 403ブロック画面で AccessBlockedException が送出されること"""
    html = "<html><head><title>403 ERROR</title></head><body><h1>Request blocked.</h1><p>Generated by cloudfront</p></body></html>"
    soup = BeautifulSoup(html, "html.parser")
    with pytest.raises(AccessBlockedException):
        check_access_blocked_or_maintenance(soup, 403, "https://example.com/test")


def test_site_maintenance_detection_emergency():
    """緊急メンテナンス画面で SiteMaintenanceException が送出されること"""
    html = "<html><head><title>重要なお知らせ・店舗情報【みずほ不動産販売】</title></head><body><h1>緊急メンテナンスのお知らせ</h1></body></html>"
    soup = BeautifulSoup(html, "html.parser")
    with pytest.raises(SiteMaintenanceException):
        check_access_blocked_or_maintenance(soup, 200, "https://example.com/test")


def test_listing_ended_detection_pure_404():
    """正規の掲載終了画面では正常に ListingEndedException が送出されること"""
    html = "<html><head><title>掲載終了いたしました</title></head><body><p>お探しの物件は掲載を終了いたしました</p></body></html>"
    soup = BeautifulSoup(html, "html.parser")
    with pytest.raises(ListingEndedException):
        ParserBase._raise_if_listing_ended(soup, "https://example.com/test")


@pytest.mark.asyncio
async def test_access_blocked_does_not_delist_property():
    """AccessBlockedException 発生時に PropertyEvaluation が delisted (is_published=False) に倒されないこと"""
    proc = ConcreteTestProc()
    proc.url = "https://example.com/item/1"
    proc.parser = proc._generateParser()

    with patch.object(proc, "_fetch_detail_item", return_value=(None, False, None)), \
         patch.object(proc, "_sync_persist_delisted") as mock_delist:
        await proc._treatPage(None)
        mock_delist.assert_not_called()


@pytest.mark.asyncio
async def test_parser_failure_sets_needs_parser_fix_and_preserves_published():
    """パーサー抽出失敗 (ParserFailureException) 発生時、is_published=False にならず needs_parser_fix=True となること"""
    proc = ConcreteTestProc()
    proc.url = "https://example.com/item/2"
    proc.parser = proc._generateParser()

    mock_eval = MagicMock()
    mock_eval.is_published = True

    with patch.object(proc, "_fetch_detail_item", return_value=(None, False, ParserFailureException("price missing"))), \
         patch.object(proc, "_find_existing_evaluation", return_value=mock_eval), \
         patch.object(proc, "_sync_persist_delisted") as mock_delist:
        await proc._treatPage(None)
        mock_delist.assert_not_called()
        assert mock_eval.needs_parser_fix is True
        assert mock_eval.needs_recrawl is True
        assert mock_eval.is_published is True
        mock_eval.save.assert_called_once()
